// Compile each raw ASCII frame once into compact RLE span tuples:
// [dy, dxStart, runLength, tokenId]
function compileFrame(def) {
    const spans = [];
    const rows = def.rows;
    const ax = def.anchorX;
    const ay = def.anchorY;

    for (let y = 0; y < rows.length; y++) {
        const row = rows[y];
        const dy = y - ay;
        let x = 0;
        const len = row.length;
        while (x < len) {
            const ch = row[x];
            const tok = TOKENS[ch] || 0;
            if (tok === 0) {
                x++;
                continue;
            }
            const startX = x;
            x++;
            while (x < len && (TOKENS[row[x]] || 0) === tok) {
                x++;
            }
            spans.push(dy, startX - ax, x - startX, tok);
        }
    }

    return Object.freeze({
        spans: Int16Array.from(spans),
        headDx: def.headX - ax,
        headDy: def.headY - ay,
        strikeDx: def.strikeX - ax,
        strikeDy: def.strikeY - ay
    });
}

export const IK_SPRITE_FRAMES = (() => {
    const compiled = {};
    const keys = Object.keys(RAW_FRAMES);
    for (let i = 0; i < keys.length; i++) {
        const k = keys[i];
        compiled[k] = compileFrame(RAW_FRAMES[k]);
    }
    return Object.freeze(compiled);
})();

