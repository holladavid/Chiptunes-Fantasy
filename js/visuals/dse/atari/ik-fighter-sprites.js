// =========================================================
// ZERO-ALLOCATION CLIPPED SPAN BLITTER & EFFECTS
// =========================================================
function fillClippedSpan(ctx, x, y, rw, rh, bufW, bufH) {
    let x0 = Math.floor(x);
    let y0 = Math.floor(y);
    let x1 = Math.floor(x + rw);
    let y1 = Math.floor(y + rh);
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > bufW) x1 = bufW;
    if (y1 > bufH) y1 = bufH;
    const cw = x1 - x0;
    const ch = y1 - y0;
    if (cw > 0 && ch > 0) {
        ctx.fillRect(x0, y0, cw, ch);
    }
}

export function drawGroundShadow(ctx, cx, groundY, jumpY, scale, bufW, bufH, minY, cShadowCore, cShadowRim) {
    const heightFactor = Math.max(0.35, 1.0 - jumpY * 0.032);
    const rx = Math.max(2, Math.floor(11 * scale * heightFactor));
    const ry = Math.max(1, Math.floor(2 * scale * (0.7 + 0.3 * heightFactor)));
    const ix = Math.floor(cx);
    const iy = Math.floor(groundY);

    ctx.fillStyle = cShadowRim;
    for (let dy = -ry; dy <= ry; dy++) {
        const py = iy + dy;
        if (py < minY || py >= bufH) continue;
        const norm = dy / (ry + 0.5);
        const span = Math.floor(rx * Math.sqrt(Math.max(0, 1 - norm * norm)));
        if (span <= 0) continue;
        fillClippedSpan(ctx, ix - span + 1, py, Math.max(1, span * 2 - 1), 1, bufW, bufH);
        if (((ix + span + py) & 1) === 0) fillClippedSpan(ctx, ix + span, py, 1, 1, bufW, bufH);
        if (((ix - span + py) & 1) === 0) fillClippedSpan(ctx, ix - span, py, 1, 1, bufW, bufH);
    }

    const coreRx = Math.max(1, Math.floor(rx * 0.65));
    ctx.fillStyle = cShadowCore;
    fillClippedSpan(ctx, ix - coreRx, iy, coreRx * 2 + 1, 1, bufW, bufH);
}

export function drawCompiledSprite(ctx, frame, paletteTable, anchorScreenX, anchorScreenY, facing, scale, bufW, bufH) {
    const spans = frame.spans;
    const ix = Math.floor(anchorScreenX);
    const iy = Math.floor(anchorScreenY);
    const flip = facing < 0;
    let lastColor = '';

    if (scale === 1) {
        for (let i = 0; i < spans.length; i += 4) {
            const tok = spans[i + 3];
            const col = paletteTable[tok];
            if (!col) continue;

            const dy = spans[i];
            const py = iy + dy;
            if (py < 0 || py >= bufH) continue;

            const dx = spans[i + 1];
            const sw = spans[i + 2];
            const px = flip ? (ix - dx - sw + 1) : (ix + dx);

            let x0 = px;
            let x1 = px + sw;
            if (x0 < 0) x0 = 0;
            if (x1 > bufW) x1 = bufW;
            const cw = x1 - x0;
            if (cw <= 0) continue;

            if (col !== lastColor) {
                ctx.fillStyle = col;
                lastColor = col;
            }
            ctx.fillRect(x0, py, cw, 1);
        }
    } else {
        for (let i = 0; i < spans.length; i += 4) {
            const tok = spans[i + 3];
            const col = paletteTable[tok];
            if (!col) continue;

            const dy = spans[i];
            const dx = spans[i + 1];
            const sw = spans[i + 2];

            const py0 = iy + Math.round(dy * scale);
            const py1 = iy + Math.round((dy + 1) * scale);
            const ch = Math.max(1, py1 - py0);

            const relX0 = flip ? -(dx + sw - 1) : dx;
            const relX1 = flip ? -(dx - 1) : (dx + sw);
            const px0 = ix + Math.round(relX0 * scale);
            const px1 = ix + Math.round(relX1 * scale);
            const cw = Math.max(1, px1 - px0);

            if (col !== lastColor) {
                ctx.fillStyle = col;
                lastColor = col;
            }
            fillClippedSpan(ctx, px0, py0, cw, ch, bufW, bufH);
        }
    }
}

